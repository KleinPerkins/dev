# WI-M5-01: primary-path discovery only — bl_discover_and_classify expands every linked
# worktree (100+ AWA/Cursor paths) and blocked doc-warden output behind the heavy main
# scan. Enumerate ~/dev primary checkouts directly; run this section before analyze_repo.
