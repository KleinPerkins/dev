# Render: stdout human report
# ---------------------------------------------------------------------------
# ---------------------------------------------------------------------------
# Unpushed-work nudge (R4/item-3): loss-risk surfacing. The laptop is the only copy of an
# unpushed commit. Loud + actionable: name each ahead repo and the exact `git push` to run.
# `ab` is "ahead/behind"; we nudge whenever ahead > 0. Advisory only — never auto-pushes.
# ---------------------------------------------------------------------------
print_push_nudge() {
  local any=0 line rel ab ahead
  while IFS=$'\t' read -r v rel class ownerrepo branch email scope dirty ab notes; do
    ahead="${ab%%/*}"
    case "$ahead" in ''|*[!0-9]*) continue ;; esac
    [ "$ahead" -gt 0 ] || continue
    if [ "$any" -eq 0 ]; then
      printf '\n⚠ UNPUSHED WORK — your laptop is the only copy of these commits. Push now:\n'
      any=1
    fi
    if [ "$rel" = "." ]; then
      printf '   • %-44s %s unpushed → git -C "%s" push\n' "$rel" "$ahead" "$ROOT"
    else
      printf '   • %-44s %s unpushed → git -C "%s/%s" push\n' "$rel" "$ahead" "$ROOT" "$rel"
    fi
  done < "$RECORDS_FILE"
  [ "$any" -eq 1 ] && printf '   (Run from each repo, or `cd ~/dev && git push`. Pushing backs your work up off this machine.)\n'
  return 0
}

print_report() {
  if [ "$DO_QUIET" -eq 1 ]; then
    printf 'dev-doctor: %s — mode: %s (run `make doctor` for the full table)\n' "$summary_line" "$mode_label"
    print_push_nudge
    [ "$n_viol" -gt 0 ] && printf 'Result: VIOLATION(s) present (exit 1).\n'
    return 0
  fi
  printf 'dev-doctor — cross-repo integrity (READ-ONLY, advisory)\n'
  printf '  root: %s   date: %s   mode: %s\n' "$ROOT" "$now" "$mode_label"
  printf '  ladder: OK < ADVISORY < DRIFT < VIOLATION\n\n'
  printf '%-9s  %-46s  %-11s  %-30s  %-16s  %-8s  %-5s  %s\n' \
         VERDICT PATH CLASS OWNER/REPO EMAIL BRANCH A/B NOTES
  printf '%-9s  %-46s  %-11s  %-30s  %-16s  %-8s  %-5s  %s\n' \
         '-------' '----' '-----' '----------' '-----' '------' '---' '-----'
  # sort: worst verdict first, then path
  while IFS=$'\t' read -r v rel class ownerrepo branch email scope dirty ab notes; do
    printf '%s\t%s\t%s\t%s\t%s\t%s\t%s\t%s\t%s\t%s\n' "$(rank "$v")" "$v" "$rel" "$class" "$ownerrepo" "$branch" "$email" "$ab" "$notes"
  done < "$RECORDS_FILE" \
  | sort -t$'\t' -k1,1nr -k3,3 \
  | while IFS=$'\t' read -r _r v rel class ownerrepo branch email ab notes; do
      printf '%-9s  %-46s  %-11s  %-30s  %-16s  %-8s  %-5s  %s\n' \
        "$v" "$(truncate_field "$rel" 46)" "$class" "$(truncate_field "$ownerrepo" 30)" \
        "$email" "$(truncate_field "$branch" 8)" "$ab" "$notes"
    done
  printf '\nSummary: %s\n' "$summary_line"
  print_push_nudge
  if [ "$n_viol" -gt 0 ]; then
    printf 'Result: VIOLATION(s) present — see rows above (exit 1). dev-doctor never blocks; this is a report.\n'
  else
    printf 'Result: no violations. (ADVISORY/DRIFT are nudges, not failures.)\n'
  fi
}

