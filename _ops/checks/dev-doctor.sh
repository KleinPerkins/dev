dw_fleet_primary_paths() {
  local root="$1" rel repo
  if git -C "$root" diff --quiet 2>/dev/null && git -C "$root" diff --cached --quiet 2>/dev/null; then
    printf '%s\n' "$root"
  fi
  for rel in personal/* capabilities/* affirm/src/* server-guard; do
    repo="$root/$rel"
    [ -e "$repo/.git" ] || continue
    printf '%s\n' "$repo"
  done
}

print_doc_warden_report() {
  local dw_cli="$SELF_DIR/../bin/doc-warden.sh"
  [ -f "$dw_cli" ] || return 0   # doc-warden not yet installed (WI-M1-03 not landed)
  [ "$DO_QUIET" -eq 1 ] || printf '\n== doc-warden documentation governance (read-only, advisory) ==\n'

  local target status rel_t ownerrepo reason check_out check_ec

  while IFS= read -r target; do
    [ -n "$target" ] && [ -d "$target" ] || continue
    if [ "$target" = "$ROOT" ]; then
      rel_t="."
    else
      IFS=$'\t' read -r status rel_t ownerrepo reason <<<"$(bl_classify_repo "$target" "$ROOT")"
      [ "$status" = "ELIGIBLE" ] || continue
    fi

    check_ec=0
    check_out="$(bash "$dw_cli" check "$target" 2>&1)" || check_ec=$?

    case "$check_ec" in
      0)  # CONFORMANT — silent in normal output, like baseline OK
          :
          ;;
      1)  # MISSING/DRIFTED/NEEDS_AUTHORING
          printf '  DOC-DRIFT      %s\n' "$rel_t"
          ;;
      3)  # NEEDS_OPERATOR or CONTRADICTORY
          if printf '%s' "$check_out" | grep -q 'CONTRADICTORY'; then
            printf '  DOC-CONTRADICTORY  %s\n' "$rel_t"
          else
            printf '  DOC-NEEDS-OPERATOR %s\n' "$rel_t"
          fi
          ;;
      *)  # Unknown exit — report as advisory, don't block
          printf '  DOC-UNKNOWN(%s) %s\n' "$check_ec" "$rel_t"
          ;;
    esac
  done < <(dw_fleet_primary_paths "$ROOT" | sort -u)

  [ "$DO_QUIET" -eq 1 ] || printf '  (Advisory only — doc-warden never changes dev-doctor exit code)\n'
  return 0
}

