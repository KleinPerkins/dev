#!/usr/bin/env bash
# _ops/checks/dev-doctor.sh — living, READ-ONLY cross-repo verifier for ~/dev.
#
# The proportional, single-user analog of cpp's integrity engine + commit-email-compliance:
# it walks every git repo under ~/dev and asserts, per repo,
#   • PLACEMENT  — owner (parsed from origin) matches its location in the tree
#                  (Affirm → affirm/{src,vendor};  KleinPerkins → personal|capabilities|root;
#                   third-party → affirm/vendor or personal run-in-place).
#   • IDENTITY   — effective commit email matches policy
#                  (KleinPerkins personal/cap repos MUST resolve to the canonical noreply;
#                   Affirm repos inherit @affirm; cpp self-governs noreply per its own people.yml;
#                   a third-party tool under personal/ authoring as @affirm is a latent leak).
#   • ORIGIN     — a defined `origin` remote exists.
#   • SYNC       — clean working tree + not ahead/behind (advisory sync nudge; never auto-push).
#   • BASELINE   — uniform repo-baseline compliance (advisory only; see _ops/baseline/README.md),
#                  via the shared _ops/bin/baseline-lib.sh checks also used by repo-baseline.sh.
#   • PR PROFILE — explicit pr-automation profile compliance/lifecycle drift (advisory only).
# and emits a verdict on the ladder  OK < ADVISORY < DRIFT < VIOLATION.
# Under --remote it ALSO prints one GLOBAL advisory: pr-automation FLEET parity — a live,
# PR-independent check that every fleet target's REMOTE committed controller_release_digest
# matches the released controller (catches stranded repos a controller bump left behind).
#
# CONTRACT: this tool is ADVISORY-ONLY. The default run makes NO changes to ANY repo
# (read-only `git`/file inspection; live `git ls-remote` under --remote is read-only too).
# It NEVER blocks a commit and NEVER pushes. It exits non-zero ONLY when a VIOLATION is found.
#
# Two explicit, opt-in side-effecting modes (they only ever write a GITIGNORED snapshot in THIS
# repo, or install non-tracked .git/hooks in sibling repos — never tracked content):
#   --write-matrix   write the "living matrix" snapshot to a GITIGNORED file (.dev-doctor/matrix.md)
#                    so it never manufactures the unpushed/dirty churn it warns about (R14/B3).
#   --fix-hooks      install the commit-time guards (identity-guard + session-lock) pre-commit
#                    (chained, idempotent, core.hooksPath-aware) across the eligible KleinPerkins
#                    personal+capability repos
#
# Usage:
#   _ops/checks/dev-doctor.sh [--remote] [--write-matrix] [--fix-hooks] [--quiet] [--root DIR]
#   make doctor                         # plain read-only report
#   --quiet                             # one-line summary only (used by `make fix-hooks`)
set -uo pipefail

SELF_DIR="$(cd "$(dirname "${BASH_SOURCE[0]:-$0}")" && pwd)"     # _ops/checks
ROOT_DEFAULT="$(cd "$SELF_DIR/../.." && pwd)"                    # repo root (~/dev)
# shellcheck source=../bin/baseline-lib.sh
. "$SELF_DIR/../bin/baseline-lib.sh"                             # uniform repo-baseline checks (shared)

CANON='49759187+KleinPerkins@users.noreply.github.com'
GUARD_MARKER='managed-by: KleinPerkins/dev identity-guard'
REG_GUARD_SRC_REL="_ops/hooks/registration-guard"
# B3/R14: the living-matrix snapshot is written to a GITIGNORED path (the ~/dev allow-list ignores
# everything not explicitly tracked, so .dev-doctor/ is never committed) — it no longer edits the
# tracked git-hygiene-audit.md and therefore cannot self-generate unpushed/dirty churn.
SNAPSHOT_REL=".dev-doctor/matrix.md"
MATRIX_BEGIN='<!-- BEGIN dev-doctor living-matrix (auto-generated by _ops/checks/dev-doctor.sh — do NOT hand-edit) -->'
MATRIX_END='<!-- END dev-doctor living-matrix -->'

ROOT="$ROOT_DEFAULT"
DO_REMOTE=0; DO_WRITE_MATRIX=0; DO_FIX_HOOKS=0; DO_QUIET=0
while [ $# -gt 0 ]; do
  case "$1" in
    --remote)        DO_REMOTE=1 ;;
    --write-matrix)  DO_WRITE_MATRIX=1 ;;
    --fix-hooks)     DO_FIX_HOOKS=1 ;;
    --quiet)         DO_QUIET=1 ;;
    --root)          shift; ROOT="${1:?--root needs a path}" ;;
    -h|--help)       sed -n '2,40p' "$0"; exit 0 ;;
    *) printf 'dev-doctor: unknown argument: %s\n' "$1" >&2; exit 2 ;;
  esac
  shift
done
ROOT="$(cd "$ROOT" && pwd)"
GIT_PROBE_TIMEOUT="${DEV_DOCTOR_GIT_TIMEOUT:-4}"

# ---------------------------------------------------------------------------
# Small helpers
# ---------------------------------------------------------------------------
lc() { printf '%s' "$1" | tr '[:upper:]' '[:lower:]'; }

# owner_of <origin-url> -> "owner/name" (best-effort; empty if unparseable)
ownerrepo_of() {
  local url="$1" rest
  case "$url" in
    *github.com[:/]*) rest="${url#*github.com}"; rest="${rest#[:/]}" ;;
    *) printf ''; return ;;
  esac
  rest="${rest%.git}"
  # keep only owner/name (first two path segments)
  printf '%s' "$rest" | awk -F/ 'NF>=2{print $1"/"$2; next}{print $0}'
}
owner_of() { ownerrepo_of "$1" | awk -F/ '{print $1}'; }

truncate_field() { local s="$1" n="$2"; if [ "${#s}" -gt "$n" ]; then printf '%s…' "${s:0:$((n-1))}"; else printf '%s' "$s"; fi; }

# git_quick <repo> <git-args...>
# Bound expensive per-repo probes so a huge vendor clone cannot make `make doctor` look hung.
# Exit 124 means timeout; stdout/stderr from successful commands is preserved.
git_quick() {
  local repo="$1"; shift
  python3 - "$GIT_PROBE_TIMEOUT" "$repo" "$@" <<'PY'
import subprocess, sys
timeout = float(sys.argv[1])
repo = sys.argv[2]
args = ["git", "-C", repo] + sys.argv[3:]
try:
    proc = subprocess.run(args, text=True, capture_output=True, timeout=timeout)
except subprocess.TimeoutExpired:
    sys.exit(124)
sys.stdout.write(proc.stdout)
sys.stderr.write(proc.stderr)
sys.exit(proc.returncode)
PY
}

# guard_state <repo> -> echoes one of:
#   active                 our chained dispatcher is the live pre-commit (guard + session-lock run)
#   missing                no guard at .git/hooks/pre-commit (and no hooksPath override)
#   inert-hookspath:<p>    core.hooksPath shadows .git/hooks; guard not installed there (R6)
#   foreign-hookspath:<p>  core.hooksPath is husky/lefthook-managed; guard needs manual chaining
#   na                     not a git repo
# Read-only: only inspects config + the active pre-commit file.
guard_state() {
  local repo="$1" hp top gd hooks pc
  top="$(git -C "$repo" rev-parse --show-toplevel 2>/dev/null)" || { printf 'na'; return; }
  gd="$(git -C "$repo" rev-parse --path-format=absolute --git-common-dir 2>/dev/null)"
  hp="$(git -C "$repo" config --get core.hooksPath 2>/dev/null || true)"
  if [ -n "$hp" ]; then
    case "$hp" in /*) hooks="$hp" ;; *) hooks="$top/$hp" ;; esac
    if grep -qF "$GUARD_MARKER" "$hooks/pre-commit" 2>/dev/null; then printf 'active'; return; fi
    case "$hp" in *.husky*|*lefthook*) printf 'foreign-hookspath:%s' "$hp" ;; *) printf 'inert-hookspath:%s' "$hp" ;; esac
    return
  fi
  if grep -qF "$GUARD_MARKER" "$gd/hooks/pre-commit" 2>/dev/null; then printf 'active'; else printf 'missing'; fi
}

active_hooks_dir() {
  local repo="$1" top gd hp
  top="$(git -C "$repo" rev-parse --show-toplevel 2>/dev/null)" || return 1
  gd="$(git -C "$repo" rev-parse --path-format=absolute --git-common-dir 2>/dev/null)" || return 1
  hp="$(git -C "$repo" config --get core.hooksPath 2>/dev/null || true)"
  if [ -n "$hp" ]; then
    case "$hp" in /*) printf '%s\n' "$hp" ;; *) printf '%s\n' "$top/$hp" ;; esac
  else
    printf '%s\n' "$gd/hooks"
  fi
}

# ---------------------------------------------------------------------------
# Repo enumeration (bounded-depth; prune heavy dirs; covers nested vendor repos)
# ---------------------------------------------------------------------------
list_repos() {
  {
    find "$ROOT" -maxdepth 6 \
      \( -name node_modules -o -name .venv -o -name venv -o -name .next -o -name dist -o -name build -o -name target \) -prune \
      -o -type d -name .git -print 2>/dev/null \
    | while IFS= read -r gd; do dirname "$gd"; done

    # Linked worktrees have a .git *file*, not a directory, and may live outside
    # ROOT (for example under ~/.cursor/worktrees). Discover them from each
    # already-known repo's common git metadata so doctor can surface dirty/ahead
    # work that would otherwise be invisible.
    find "$ROOT" -maxdepth 6 \
      \( -name node_modules -o -name .venv -o -name venv -o -name .next -o -name dist -o -name build -o -name target \) -prune \
      -o -type d -name .git -print 2>/dev/null \
    | while IFS= read -r gd; do
        repo="$(dirname "$gd")"
        git -C "$repo" worktree list --porcelain 2>/dev/null \
          | awk '/^worktree /{sub(/^worktree /,""); print}'
      done
  } | sort -u
}

# ---------------------------------------------------------------------------
# Per-repo analysis. Emits one TAB-separated record:
#   verdict \t rel \t class \t ownerrepo \t branch \t emaillabel \t scope \t dirty \t ab \t notes
# ---------------------------------------------------------------------------
analyze_repo() {
  local repo="$1"
  local rel; if [ "$repo" = "$ROOT" ]; then rel="."; else rel="${repo#"$ROOT"/}"; fi

  local origin ownerrepo owner owner_lc
  origin="$(git -C "$repo" config --get remote.origin.url 2>/dev/null || true)"
  ownerrepo="$(ownerrepo_of "$origin")"
  owner="$(owner_of "$origin")"; owner_lc="$(lc "$owner")"

  # placement bucket
  local place
  case "$rel" in
    .)                place=root ;;
    affirm/src/*)     place=affirm-src ;;
    affirm/vendor/*)  place=affirm-vendor ;;
    affirm/*)         place=affirm-other ;;
    capabilities/*)   place=capabilities ;;
    personal/*)       place=personal ;;
    *)                place=other ;;
  esac

  # cpp self-governance carve-out (Affirm repo that intentionally sets a LOCAL noreply
  # via its own _ops/facts/people.yml — see SOT). Match by path or origin.
  local is_cpp=0
  case "$rel" in affirm/src/card-platform-product) is_cpp=1 ;; esac
  [ "$(lc "$ownerrepo")" = "affirm/card-platform-product" ] && is_cpp=1

  # identity
  local email_local email_eff scope emaillabel is_noreply=0
  email_local="$(git -C "$repo" config --local --get user.email 2>/dev/null || true)"
  email_eff="$(git -C "$repo" config --get user.email 2>/dev/null || true)"
  if [ -n "$email_local" ]; then scope=local; else scope=inherit; fi
  [ "$email_eff" = "$CANON" ] && is_noreply=1
  if [ "$is_noreply" -eq 1 ]; then emaillabel=noreply
  elif [ -z "$email_eff" ]; then emaillabel='<unset>'
  elif printf '%s' "$email_eff" | grep -qi '@affirm\.com$'; then emaillabel='@affirm'
  else emaillabel="$email_eff"; fi

  # sync state
  local branch dirty ab
  branch="$(git -C "$repo" rev-parse --abbrev-ref HEAD 2>/dev/null || echo '?')"
  local status_out status_rc=0
  status_out="$(git_quick "$repo" status --porcelain 2>/dev/null)" || status_rc=$?
  if [ "$status_rc" -eq 124 ]; then
    dirty=unknown
  elif [ -n "$status_out" ]; then
    dirty=yes
  else
    dirty=no
  fi
  ab="$(repo_ab "$repo")"

  # class label (for the matrix)
  local class
  case "$place" in
    root)           class=home ;;
    affirm-src)     if [ "$is_cpp" -eq 1 ]; then class=gov; else class=src; fi ;;
    affirm-vendor)  class=vendor ;;
    affirm-other)   class=affirm ;;
    capabilities)   class=cap ;;
    personal)       if [ "$owner_lc" = "kleinperkins" ]; then class=pers; else class=pers-vendor; fi ;;
    *)              class=repo ;;
  esac

  # ----- verdict + notes -----
  local verdict=OK; local -a notes=()
  raise() { local v="$1"; [ "$(rank "$v")" -gt "$(rank "$verdict")" ] && verdict="$v"; }

  # ORIGIN
  if [ -z "$origin" ]; then raise DRIFT; notes+=("no origin remote"); fi

  # PLACEMENT
  if [ "$owner_lc" = "affirm" ] && [ "$rel" != "." ]; then
    case "$place" in affirm-src|affirm-vendor|affirm-other) : ;; *) raise DRIFT; notes+=("Affirm repo outside affirm/") ;; esac
  fi
  if [ "$owner_lc" = "kleinperkins" ]; then
    case "$place" in affirm-src|affirm-vendor|affirm-other) raise DRIFT; notes+=("KleinPerkins repo under affirm/") ;; esac
  fi

  # IDENTITY
  if [ "$is_cpp" -eq 1 ]; then
    notes+=("cpp self-governed identity")
  elif [ "$owner_lc" = "kleinperkins" ]; then
    if [ "$is_noreply" -ne 1 ]; then raise VIOLATION; notes+=("KleinPerkins repo email ${emaillabel} != canonical noreply"); fi
  elif [ "$owner_lc" = "affirm" ]; then
    if [ "$is_noreply" -eq 1 ]; then
      case "$class" in
        vendor) notes+=("vendor read-only identity override") ;;
        *) raise ADVISORY; notes+=("stray noreply override on an Affirm repo") ;;
      esac
    fi
  elif [ -n "$owner" ]; then
    # third-party
    if [ "$place" = "personal" ]; then
      if [ "$is_noreply" -ne 1 ]; then raise ADVISORY; notes+=("3p tool under personal/ authoring as ${emaillabel} (latent leak; we don't commit)"); fi
    else
      if [ "$is_noreply" -eq 1 ]; then notes+=("vendor read-only identity override"); fi
    fi
  fi

  # HOOKS / GUARD (R6): a KleinPerkins personal/cap repo must have a LIVE commit-time guard.
  # core.hooksPath silently shadows .git/hooks, leaving the guard inert — surface it loudly.
  local hookspath gstate
  hookspath="$(git -C "$repo" config --get core.hooksPath 2>/dev/null || true)"
  if [ "$is_cpp" -ne 1 ] && [ "$rel" != "." ] && [ "$owner_lc" = "kleinperkins" ]; then
    case "$place" in personal|capabilities)
      gstate="$(guard_state "$repo")"
      case "$gstate" in
        active)
          ah="$(active_hooks_dir "$repo" || true)"
          src="$ROOT/$REG_GUARD_SRC_REL"
          if [ -n "$ah" ] && [ -f "$src" ]; then
            if [ ! -f "$ah/registration-guard" ]; then
              raise ADVISORY; notes+=("registration-guard missing from active hooksPath (run: make fix-hooks)")
            elif ! cmp -s "$src" "$ah/registration-guard"; then
              raise ADVISORY; notes+=("registration-guard stale in active hooksPath (run: make fix-hooks)")
            fi
          fi
          ;;
        missing)               raise ADVISORY; notes+=("commit-guard NOT installed (run: make fix-hooks)") ;;
        inert-hookspath:*)     raise DRIFT;    notes+=("core.hooksPath=${gstate#inert-hookspath:} SHADOWS the guard — it is inert (run: make fix-hooks)") ;;
        foreign-hookspath:*)   raise ADVISORY; notes+=("core.hooksPath=${gstate#foreign-hookspath:} (husky/lefthook) — guard needs manual chaining (run: make fix-hooks)") ;;
      esac
    ;; esac
  elif [ -n "$hookspath" ]; then
    # informational for everything else (e.g. openflowkit's .husky/_ — out of guard scope, but flagged)
    notes+=("core.hooksPath=$hookspath")
  fi

  # BASELINE (advisory only; read-only; never DRIFT/VIOLATION). Reuses repo-baseline's own
  # classification + compliance checks via baseline-lib.sh so the logic is defined once.
  # See _ops/baseline/README.md. Excluded-by-hard-rule repos (vendor, cpp, chaos-scheduler,
  # external origin, umbrella) are intentionally silent here — dirty/branch exclusions are already
  # surfaced by the SYNC notes below, so this stays non-redundant.
  local bl_status bl_rel bl_ownerrepo bl_reason
  IFS=$'\t' read -r bl_status bl_rel bl_ownerrepo bl_reason <<<"$(bl_classify_repo "$repo" "$ROOT")"
  if [ "$bl_status" = "ELIGIBLE" ]; then
    local bl_verdict; bl_verdict="$(bl_baseline_verdict "$repo")"
    local shard_observation
    if ! shard_observation="$(python3 "$ROOT/_ops/bin/test-sharding.py" view --repo "$repo" 2>&1)"; then
      raise DRIFT; notes+=("TEST_SHARDING_DRIFT: $shard_observation")
    elif printf '%s' "$shard_observation" | grep -q '"activation_allowed": false'; then
      raise ADVISORY; notes+=("test sharding pending; verification activation is blocked")
    fi
    case "$bl_verdict" in
      MISSING) raise ADVISORY; notes+=("baseline not applied (run: repo-baseline.sh apply $rel)") ;;
      PARTIAL) raise ADVISORY; notes+=("baseline partial (run: repo-baseline.sh verify $rel)") ;;
    esac
    # GitHub-side ruleset (advisory only; read-only). Only surfaced once local files are already
    # COMPLIANT, to avoid double-noting the same repo for two different reasons at once.
    if [ "$bl_verdict" = "COMPLIANT" ]; then
      local bl_gh_status bl_gh_detail
      IFS=$'\t' read -r bl_gh_status bl_gh_detail <<<"$(bl_github_controls "${bl_ownerrepo:-}")"
      case "$bl_gh_status" in
        REQUIRED) raise ADVISORY; notes+=("history ruleset not observed; repository-owned settings admission required") ;;
      esac
    fi

    # D2 (2026-07-30): review-policy drift — LOUD by design (DRIFT, not ADVISORY), unlike the
    # local-file MISSING/PARTIAL/COMPLIANT verdict above. Independent of local-file compliance and
    # of the GitHub Pro plan gate above it: a required-human-review rule reappearing on ANY
    # ruleset silently breaks the reviewer App's squash auto-merge fleet-wide, so it is raised
    # every time it's found, not buried behind other conditions. See bl_check_no_required_reviews
    # in baseline-lib.sh and _ops/baseline/profiles/pr-automation/v3/README.md (D1(b)).
    local bl_review_status bl_review_detail
    IFS=$'\t' read -r bl_review_status bl_review_detail <<<"$(bl_check_delivery_review_policy "$repo" "${bl_ownerrepo:-}")"
    if [ "$bl_review_status" = "REVIEW_DRIFT" ]; then
      raise DRIFT; notes+=("REVIEW_DRIFT: required-review ruleset detected — $bl_review_detail (run: repo-baseline.sh verify $rel)")
    elif [ "$bl_review_status" = DELIVERY_DRIFT ]; then
      raise DRIFT; notes+=("DELIVERY_DRIFT: $bl_review_detail")
    elif [ "$bl_review_status" = NATIVE_REPOSITORY_OWNED ]; then
      notes+=("native delivery: repository-owned verification remains separate")
    fi
  fi

  local successor_status successor_detail
  IFS=$'\t' read -r successor_status successor_detail <<<"$(bl_check_delivery_review_policy "$repo")"
  case "$successor_status" in
    DELIVERY_DRIFT) raise DRIFT ;;
    *) raise ADVISORY ;;
  esac
  notes+=("$successor_status: $successor_detail")

  # SYNC (advisory only)
  if [ "$dirty" = yes ]; then raise ADVISORY; notes+=("uncommitted changes"); fi
  if [ "$dirty" = unknown ]; then raise ADVISORY; notes+=("git status timed out after ${GIT_PROBE_TIMEOUT}s; rerun scoped or inspect manually"); fi
  case "$ab" in 0/0|—|"") : ;; *) raise ADVISORY; notes+=("out of sync $ab") ;; esac

  # CONTINUAL-LEARNING MEMORY (migration invariant): agent-learnings.md must be git-ignored and
  # never tracked; tracked AGENTS.md must carry no machine '## Learned *' blocks and should point
  # to agent-learnings.md. Guard git calls — a bare-repo misconfig returns rc 128 (INDETERMINATE).
  local al_present al_tracked ci_rc
  al_present=0; [ -f "$repo/agent-learnings.md" ] && al_present=1
  al_tracked="$(git -C "$repo" ls-files -- agent-learnings.md 2>/dev/null || true)"
  if [ -n "$al_tracked" ]; then
    raise VIOLATION; notes+=("agent-learnings.md is TRACKED — machine memory must never be committed")
  elif [ "$al_present" -eq 1 ]; then
    git -C "$repo" check-ignore -q agent-learnings.md 2>/dev/null; ci_rc=$?
    case "$ci_rc" in
      0) : ;;
      1) raise DRIFT; notes+=("agent-learnings.md present but NOT git-ignored") ;;
      *) notes+=("agent-learnings.md present; ignore-state indeterminate (git rc=$ci_rc)") ;;
    esac
  fi
  if [ -n "$(git -C "$repo" ls-files -- AGENTS.md 2>/dev/null || true)" ]; then
    if grep -qE '^## Learned (User Preferences|Workspace Facts)\b' "$repo/AGENTS.md" 2>/dev/null; then
      raise DRIFT; notes+=("AGENTS.md still carries machine '## Learned *' blocks (migration incomplete)")
    elif ! grep -qF 'agent-learnings.md' "$repo/AGENTS.md" 2>/dev/null; then
      raise ADVISORY; notes+=("AGENTS.md has no agent-learnings.md pointer")
    fi
  fi

  # join notes with "; " (safe under set -u for empty arrays)
  local notestr="" j
  if [ "${#notes[@]}" -gt 0 ]; then
    for j in "${!notes[@]}"; do
      if [ "$j" -eq 0 ]; then notestr="${notes[$j]}"; else notestr="$notestr; ${notes[$j]}"; fi
    done
  fi

  printf '%s\t%s\t%s\t%s\t%s\t%s\t%s\t%s\t%s\t%s\n' \
    "$verdict" "$rel" "$class" "${ownerrepo:-<none>}" "$branch" "$emaillabel" "$scope" "$dirty" "$ab" "$notestr"
}

rank() { case "$1" in OK) echo 0 ;; ADVISORY) echo 1 ;; DRIFT) echo 2 ;; VIOLATION) echo 3 ;; *) echo 0 ;; esac; }

# repo_ab <repo> -> "ahead/behind" string ("0/0", "1/2", "—" no upstream).
# Default: from the local tracking ref (last fetch, no network).
# --remote: best-effort live compare of the current branch tip vs origin (read-only ls-remote).
repo_ab() {
  local repo="$1" up ahead behind counts
  if [ "$DO_REMOTE" -eq 1 ]; then
    local br rem_sha loc_sha
    br="$(git -C "$repo" rev-parse --abbrev-ref HEAD 2>/dev/null || true)"
    loc_sha="$(git -C "$repo" rev-parse HEAD 2>/dev/null || true)"
    if [ -n "$br" ] && [ "$br" != HEAD ]; then
      rem_sha="$(GIT_TERMINAL_PROMPT=0 GIT_SSH_COMMAND='ssh -o BatchMode=yes -o ConnectTimeout=6' \
                 git -C "$repo" ls-remote --heads origin "$br" 2>/dev/null | awk 'NR==1{print $1}')"
      if [ -n "$rem_sha" ]; then
        if [ "$rem_sha" = "$loc_sha" ]; then printf '0/0'; else printf 'live≠'; fi
        return
      fi
    fi
    # fall through to local tracking info if the live probe was inconclusive
  fi
  up="$(git -C "$repo" rev-parse --abbrev-ref --symbolic-full-name '@{u}' 2>/dev/null || true)"
  if [ -z "$up" ]; then printf '—'; return; fi
  counts="$(git_quick "$repo" rev-list --left-right --count '@{u}...HEAD' 2>/dev/null || true)"
  [ -n "$counts" ] || { printf '?/?'; return; }
  behind="$(printf '%s' "$counts" | awk '{print $1+0}')"
  ahead="$(printf '%s' "$counts" | awk '{print $2+0}')"
  printf '%s/%s' "${ahead:-0}" "${behind:-0}"
}

